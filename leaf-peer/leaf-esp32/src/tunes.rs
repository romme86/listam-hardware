//! Short monophonic 8-bit arrangements for the GPIO7 passive piezo.
//!
//! These are intentionally compact motifs rather than complete soundtracks:
//! they fit the Leaf's one-voice square-wave output and make useful hardware
//! demos without burdening the normal Leaf runtime with sampled audio.

#[derive(Clone, Copy)]
pub struct Note {
    pub frequency_hz: u32,
    pub duration_ms: u32,
}

#[derive(Clone, Copy)]
pub struct Tune {
    pub title: &'static str,
    pub notes: &'static [Note],
}

const fn n(frequency_hz: u32, duration_ms: u32) -> Note {
    Note {
        frequency_hz,
        duration_ms,
    }
}

